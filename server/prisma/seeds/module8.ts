export const M8_THEORY = `## Покажчики та посилання

У C++ кожна змінна зберігається у **пам'яті** комп'ютера і має свою унікальну адресу (як номер будинку на вулиці).

### Що таке покажчик?
**Покажчик (pointer)** — це змінна, яка зберігає не саме значення (як 5 або 10), а **адресу** іншої змінної в пам'яті.
Для роботи з покажчиками використовують два спеціальні символи:
1. \`&\` (амперсанд) — отримати адресу змінної.
2. \`*\` (зірочка) — оголосити покажчик, або отримати значення за адресою.

\`\`\`cpp
int x = 42;
int* ptr = &x; // ptr тепер зберігає адресу змінної x
\`\`\`

### Що таке посилання?
**Посилання (reference)** — це просто інше ім'я (псевдонім) для існуючої змінної. Усе, що ви робите з посиланням, відбувається з оригінальною змінною!

\`\`\`cpp
int y = 100;
int& ref = y;  // ref — це посилання на y

ref = 200; // Тепер і y дорівнює 200!
\`\`\`

> **Ключова різниця:**
> Покажчик (\`*\`) може змінювати адресу, на яку він вказує, або бути порожнім (\`nullptr\`).
> Посилання (\`&\`) завжди прив'язане до однієї змінної від моменту створення і не може бути порожнім.
`;

